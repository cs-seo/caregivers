/**
 * Serialise JSON-LD for embedding in a <script> tag. We escape the characters
 * that could break out of the script element or be interpreted as HTML so that
 * user-supplied fields (carer bios, names, reviews) can never inject markup.
 */
function safeJsonLd(data: unknown) {
  return JSON.stringify(data)
    .replace(/</g, "\\u003c")
    .replace(/>/g, "\\u003e")
    .replace(/&/g, "\\u0026")
    .replace(/\u2028/g, "\\u2028")
    .replace(/\u2029/g, "\\u2029");
}

export function JsonLd({ data }: { data: unknown }) {
  return (
    <script
      type="application/ld+json"
      dangerouslySetInnerHTML={{ __html: safeJsonLd(data) }}
    />
  );
}
